# Этот класс задает стандартные методы, которые должны быть в любой стратегии.
# Он обеспечивает единообразие взаимодействия между движком и кодом стратегии.
class BaseStrategy:
    def __init__(self, config: dict):
        """
        Инициализация стратегии.
        Принимает словарь настроек (config), загруженный из JSON-файла.
        """
        self.config = config
        self.position = None  # Текущая позиция: 'LONG', 'SHORT' или None
        self.balance = config.get('initial_balance', 1000)
        self.trades = []      # История сделок

    def on_candle(self, candle: dict):
        """
        Вызывается каждый раз при поступлении новой свечи.
        Здесь должна быть основная логика принятия решений.
        """
        raise NotImplementedError("Метод on_candle должен быть реализован в дочернем классе")

    def get_state(self):
        """
        Возвращает текущее состояние стратегии для отображения в интерфейсе.
        """
        return {
            "position": self.position,
            "balance": self.balance,
            "trades_count": len(self.trades)
        }